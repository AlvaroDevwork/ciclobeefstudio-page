function assertUnique(field) {
    const values = registry.map(product => product[field]);
    if (new Set(values).size !== values.length) {
        throw new Error(`Duplicate Shopify product registry field: ${field}`);
    }
}

if (registry.length !== 19) {
    throw new Error(`Expected 19 Shopify products, received ${registry.length}`);
}

["key", "productId", "componentId"].forEach(assertUnique);

const groupKeys = PRODUCT_GROUPS.map(group => group.key);
if (new Set(groupKeys).size !== groupKeys.length) {
    throw new Error("Duplicate Shopify product group key.");
}

if (registry.some(product => !groupKeys.includes(product.group))) {
    throw new Error("Every Shopify product must belong to a customer-facing group.");
}

if (registry.some(product => !product.title || !product.summary || !product.image?.src || !product.image?.alt)) {
    throw new Error("Every Shopify product must include complete customer-facing metadata.");
}

if (registry.some(product => product.previews?.some(preview => !preview.src || !preview.alt || !preview.width || !preview.height))) {
    throw new Error("Every catalog preview must include a source, alt text, width, and height.");
}

export const PRODUCT_REGISTRY = Object.freeze(
    registry.map(product => Object.freeze({
        ...product,
        image: Object.freeze(product.image),
        previews: product.previews
            ? Object.freeze(product.previews.map(preview => Object.freeze(preview)))
            : undefined,
    })),
);

export function getProductByKey(key) {
    return PRODUCT_REGISTRY.find(product => product.key === key) ?? null;
}
